// ============================================================================
// GuidedToolStep.swift - the tool decision written under guided generation
// (#533) instead of as free text. Pure ApfelCore: builds the step schema and
// the instructions, and reads the step back. The server runs it against the
// model (Sources/GuidedToolCalling.swift).
//
// Why: in the free-text format the on-device model writes the tool-call
// envelope itself, and small wording changes in the tool list flip it between
// the documented envelope, flat variants, broken escaping, invented argument
// names and calls for prompts that need none (#580, #581). Under guided
// generation the model only picks an action from an enum and fills arguments
// whose names come from the tool's schema, so it cannot invent keys or break
// the JSON. Measured on macOS 27.0.1 (M2, 2026-11-17) with the #580/#581
// tool sets: see docs/tool-calling-guide.md.
// ============================================================================

import Foundation

/// One guided tool step: the schema the model's decision is generated
/// under, the instructions that go with it, and the parser for the result.
package struct GuidedToolStep: Sendable {

    /// The model's decision for this turn.
    package enum Decision: Sendable, Equatable {
        /// Reply to the user in plain text (generated by a separate request).
        case answer
        /// Call `name`. `arguments` is compact JSON, or nil when the model
        /// left the tool's arguments slot out of the step.
        case call(name: String, arguments: String?)
    }

    /// Why the guided step cannot run for a request; the server then uses
    /// the free-text format.
    package struct Unavailable: Error, Sendable, Equatable {
        package let reason: String
    }

    /// The `action` value that means "reply to the user". `answer` unless a
    /// tool already has that name.
    package let answerAction: String
    /// The JSON Schema text the step is generated under.
    package let schemaJSON: String
    /// The instructions block: the tool list plus how to decide.
    package let instructions: String

    private let toolNames: [String]
    private let lenientParameters: [String: String]

    /// Build the step for the tools in scope under a policy mode.
    /// - Throws: `Unavailable` when no tool is in scope or a tool's
    ///   `parameters` cannot be read as a JSON Schema object.
    package init(tools: [ToolDef], mode: ToolPolicy.Mode) throws {
        let offered: [ToolDef]
        switch mode {
        case .disabled:
            throw Unavailable(reason: "no tools are in scope")
        case .specific(let name):
            offered = tools.filter { $0.name == name }
        case .auto, .required:
            offered = tools
        }
        guard !offered.isEmpty else { throw Unavailable(reason: "no tools are in scope") }

        var lenient: [String: String] = [:]
        var argumentSlots: [String: Any] = [:]
        for tool in offered {
            guard let raw = tool.parametersJSON?.trimmingCharacters(in: .whitespacesAndNewlines), !raw.isEmpty else {
                continue
            }
            guard let schemaText = Self.lenientSchemaJSON(raw),
                  let schema = Self.jsonObject(schemaText) else {
                throw Unavailable(reason: "the parameters of tool '\(tool.name)' are not a JSON Schema object")
            }
            lenient[tool.name] = schemaText
            if let properties = schema["properties"] as? [String: Any], !properties.isEmpty {
                argumentSlots[tool.name] = schema
            }
        }

        let names = offered.map(\.name)
        var answer = "answer"
        for candidate in ["answer", "reply_to_user", "respond_to_user"] where !names.contains(candidate) {
            answer = candidate
            break
        }
        let allowsAnswer: Bool
        if case .auto = mode { allowsAnswer = true } else { allowsAnswer = false }

        let schema: [String: Any] = [
            "type": "object",
            "properties": [
                "action": [
                    "type": "string",
                    "enum": names + (allowsAnswer ? [answer] : []),
                    "description": allowsAnswer
                        ? "The tool to call now, or \(answer) to reply to the user."
                        : "The tool to call now.",
                ] as [String: Any],
                "arguments": [
                    "type": "object",
                    "description": "The arguments of the tool named in action, under its name.",
                    "properties": argumentSlots,
                    "required": [String](),
                ] as [String: Any],
            ] as [String: Any],
            "required": ["action"],
        ]

        self.answerAction = answer
        self.toolNames = names
        self.lenientParameters = lenient
        self.schemaJSON = Self.compactJSON(schema) ?? "{}"
        self.instructions = ToolCallHandler.buildToolSchemaPrompt(tools: offered) + "\n\n"
            + Self.decisionText(mode: mode, answer: answer)
    }

    /// Read the model's step. Nil when the text is not a step for one of the
    /// offered actions (guided generation makes that a runtime fault).
    package func parse(_ json: String) -> Decision? {
        guard let step = Self.jsonObject(json), let action = step["action"] as? String else { return nil }
        if action == answerAction, !toolNames.contains(action) { return .answer }
        guard toolNames.contains(action) else { return nil }
        let slot = (step["arguments"] as? [String: Any])?[action]
        if let object = slot as? [String: Any] {
            return .call(name: action, arguments: Self.compactJSON(object))
        }
        // A tool without declared properties has no slot: no arguments.
        if lenientParameters[action].flatMap(Self.jsonObject).map({ ($0["properties"] as? [String: Any])?.isEmpty ?? true }) ?? true {
            return .call(name: action, arguments: "{}")
        }
        return .call(name: action, arguments: nil)
    }

    /// The follow-up request for a call whose arguments the step left out or
    /// got wrong: a prompt naming the tool and the tool's own (lenient)
    /// parameter schema, so its required arguments are generated. Nil for an
    /// unknown tool.
    package func argumentsRequest(for name: String) -> (prompt: String, schemaJSON: String)? {
        guard toolNames.contains(name) else { return nil }
        let schema = lenientParameters[name] ?? #"{"type":"object","properties":{}}"#
        return ("Write the arguments for \(name).", schema)
    }

    // MARK: - Instructions

    private static func decisionText(mode: ToolPolicy.Mode, answer: String) -> String {
        switch mode {
        case .specific(let name):
            return "Call the tool \(name) now: set action to \(name) and write its arguments under arguments.\(name)."
        case .required:
            return "Call one of the tools now: set action to its name and write its arguments under arguments.<its name>."
        case .auto, .disabled:
            return "Decide the next step. Call a tool only when the user's request needs what the tool provides. "
                + "For greetings, small talk and requests you can answer yourself, such as writing or explaining, "
                + "set action to \"\(answer)\". To call a tool, set action to its name and write its arguments "
                + "under arguments.<its name>."
        }
    }

    // MARK: - Lenient schemas

    /// Keywords apfel's guided generation rejects (docs/openai-api-
    /// compatibility.md, "Rejected"). A tool schema is a description for
    /// the model, not a response_format contract, so these are dropped from
    /// the copy the step is generated under instead of failing the request;
    /// the returned arguments are still checked against the original schema
    /// (ToolPolicy.evaluate(output:)).
    private static let droppedKeywords: Set<String> = [
        "multipleOf", "minLength", "maxLength", "pattern",
        "contentEncoding", "contentMediaType", "contentSchema",
        "uniqueItems", "contains", "minContains", "maxContains", "prefixItems", "additionalItems",
        "minProperties", "maxProperties", "patternProperties", "propertyNames",
        "dependentRequired", "dependentSchemas", "dependencies",
    ]

    /// A copy of a JSON Schema object without the keywords guided generation
    /// rejects. Nil when the text is not a JSON object.
    package static func lenientSchemaJSON(_ json: String) -> String? {
        guard let schema = jsonObject(json) else { return nil }
        return compactJSON(lenient(schema))
    }

    private static func lenient(_ node: [String: Any]) -> [String: Any] {
        var out: [String: Any] = [:]
        for (key, value) in node {
            if droppedKeywords.contains(key) { continue }
            switch key {
            case "additionalProperties", "unevaluatedProperties", "unevaluatedItems":
                if value is Bool { out[key] = value }
            case "enum":
                if let values = value as? [Any], values.allSatisfy({ $0 is String }) { out[key] = value }
            case "const":
                if value is String { out[key] = value }
            case "properties", "$defs", "definitions":
                if let map = value as? [String: Any] {
                    out[key] = map.mapValues { ($0 as? [String: Any]).map(lenient) ?? $0 }
                } else {
                    out[key] = value
                }
            case "items":
                out[key] = (value as? [String: Any]).map(lenient) ?? value
            case "anyOf", "oneOf":
                out[key] = (value as? [Any])?.map { ($0 as? [String: Any]).map(lenient) ?? $0 } ?? value
            default:
                out[key] = value
            }
        }
        return out
    }

    // MARK: - JSON helpers

    private static func jsonObject(_ text: String) -> [String: Any]? {
        (try? JSONSerialization.jsonObject(with: Data(text.utf8))) as? [String: Any]
    }

    private static func compactJSON(_ object: Any) -> String? {
        guard let data = try? JSONSerialization.data(
                withJSONObject: object, options: [.sortedKeys, .withoutEscapingSlashes]) else { return nil }
        return String(data: data, encoding: .utf8)
    }
}
